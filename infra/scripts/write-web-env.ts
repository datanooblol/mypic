/**
 * Turn CDK outputs into web/.env.local for local Next.js development.
 * Usage: npm run env:web [-- prod]   (after npm run deploy:dev)
 */
import * as fs from 'node:fs';
import * as path from 'node:path';

type Outputs = Record<string, Record<string, string>>;

const stage = process.argv[2] ?? 'dev';
const prefix = `MyPic-${stage}`;
const outputsPath = path.join(__dirname, '..', `cdk-outputs.${stage}.json`);

if (!fs.existsSync(outputsPath)) {
  console.error(`Missing ${outputsPath}. Run "npm run deploy:${stage}" first.`);
  process.exit(1);
}

const outputs = JSON.parse(fs.readFileSync(outputsPath, 'utf8')) as Outputs;
const get = (stack: string, key: string): string => {
  const value = outputs[`${prefix}-${stack}`]?.[key];
  if (!value) throw new Error(`Output ${prefix}-${stack}.${key} not found`);
  return value;
};
const optional = (stack: string, key: string) => outputs[`${prefix}-${stack}`]?.[key] ?? '';

const lines = [
  `# Generated by infra/scripts/write-web-env.ts from ${path.basename(outputsPath)}`,
  `NEXT_PUBLIC_STAGE=${stage}`,
  `NEXT_PUBLIC_AWS_REGION=${get('Auth', 'Region')}`,
  `NEXT_PUBLIC_USER_POOL_ID=${get('Auth', 'UserPoolId')}`,
  `NEXT_PUBLIC_USER_POOL_CLIENT_ID=${get('Auth', 'UserPoolClientId')}`,
  `NEXT_PUBLIC_API_URL=${optional('Api', 'ApiUrl')}`,
  '',
];

const target = path.join(__dirname, '..', '..', 'web', '.env.local');
fs.writeFileSync(target, lines.join('\n'));
console.log(`Wrote ${target}`);
